def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def git(repo: Path, *args: str, text: bool = True) -> str | bytes:
    proc = subprocess.run(
        ["git", "-C", str(repo), *args],
        check=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=text,
    )
    return proc.stdout


def commit_meta(repo: Path, commit: str) -> dict[str, Any]:
    raw = str(git(repo, "show", "-s", "--format=%H%x00%aI%x00%cI%x00%P%x00%s", commit))
    sha, author_date, commit_date, parents, subject = raw.rstrip("\n").split("\x00")
    return {
        "commit": sha,
        "author_date": author_date,
        "commit_date": commit_date,
        "parents": parents.split() if parents else [],
        "parent_count": len(parents.split()) if parents else 0,
        "subject": subject,
    }


def blob_record(repo: Path, commit: str, path: str) -> dict[str, Any]:
    exists = subprocess.run(
        ["git", "-C", str(repo), "cat-file", "-e", f"{commit}:{path}"],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    ).returncode == 0
    if not exists:
        return {"present": False}
    data = bytes(git(repo, "show", f"{commit}:{path}", text=False))
    blob = str(git(repo, "rev-parse", f"{commit}:{path}")).strip()
    return {
        "present": True,
        "git_blob": blob,
        "sha256": sha256_bytes(data),
        "line_count": data.count(b"\n") + (0 if data.endswith(b"\n") or not data else 1),
    }


def parse_name_status(raw: str) -> list[dict[str, str]]:
    records: list[dict[str, str]] = []
    for line in raw.splitlines():
        if not line:
            continue
        fields = line.split("\t")
        status = fields[0]
        if status.startswith(("R", "C")):
            require(len(fields) == 3, f"bad rename/copy status: {line}")
            records.append({"status": status, "old_path": fields[1], "path": fields[2]})
        else:
            require(len(fields) == 2, f"bad name status: {line}")
            records.append({"status": status, "path": fields[1]})
    return records


def tracked_paths_with_renames(repo: Path) -> tuple[str, ...]:
    tracked = set(PATHS)
    while True:
        commits = str(
            git(repo, "log", "--reverse", "--format=%H", f"{BASE}..{HEAD}", "--", *sorted(tracked))
        ).splitlines()
        added: set[str] = set()
        for commit in commits:
            meta = commit_meta(repo, commit)
            if not meta["parents"]:
                continue
            raw = str(
                git(
                    repo,
                    "diff-tree",
                    "--no-commit-id",
                    "-r",
                    "-M",
                    "--name-status",
                    meta["parents"][0],
                    commit,
                )
            )
            for record in parse_name_status(raw):
                if record["status"].startswith("R") and record["old_path"] in tracked:
                    added.add(record["path"])
        if not (added - tracked):
            return tuple(sorted(tracked))
        tracked |= added


def vocabulary_matches(text: str) -> list[str]:
    lower = text.lower()
    return [term for term in VOCABULARY if term.lower() in lower]


def history(repo: Path, tracked: tuple[str, ...]) -> list[dict[str, Any]]:
    commits = str(
        git(repo, "log", "--reverse", "--format=%H", f"{BASE}..{HEAD}", "--", *tracked)
    ).splitlines()
    out: list[dict[str, Any]] = []
    for commit in commits:
        meta = commit_meta(repo, commit)
        require(meta["parents"], f"unexpected root commit in range: {commit}")
        parent = meta["parents"][0]
        raw_status = str(
            git(
                repo,
                "diff-tree",
                "--no-commit-id",
                "-r",
                "-M",
                "--name-status",
                parent,
                commit,
                "--",
                *tracked,
            )
        )
        changes = parse_name_status(raw_status)
        require(changes, f"path-selected commit has no retained changes: {commit}")
        patch = str(git(repo, "diff", "--find-renames", parent, commit, "--", *tracked))
        meta["changes"] = changes
        meta["subject_vocabulary_matches"] = vocabulary_matches(meta["subject"])
        meta["patch_vocabulary_matches"] = vocabulary_matches(patch)
        meta["patch_sha256"] = sha256_bytes(patch.encode("utf-8"))
        out.append(meta)
    require(len({item["commit"] for item in out}) == len(out), "duplicate history commit")
    return out


def source(repo: Path, path: str) -> str:
    return str(git(repo, "show", f"{HEAD}:{path}"))


def require_fragments(text: str, path: str, fragments: tuple[str, ...]) -> None:
    for fragment in fragments:
        require(fragment in text, f"{path}: required fragment missing: {fragment}")


