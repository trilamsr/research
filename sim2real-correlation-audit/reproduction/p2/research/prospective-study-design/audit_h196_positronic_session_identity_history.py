def build(repo: Path) -> dict[str, Any]:
    require(repo.is_dir(), f"repository missing: {repo}")
    require(str(git(repo, "rev-parse", BASE)).strip() == BASE, "baseline commit mismatch")
    require(str(git(repo, "rev-parse", HEAD)).strip() == HEAD, "comparison commit mismatch")
    subprocess.run(
        ["git", "-C", str(repo), "merge-base", "--is-ancestor", BASE, HEAD],
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    require(not str(git(repo, "status", "--porcelain=v1")).strip(), "source checkout is dirty")
    require(sha256_file(H195_RESULT) == H195_RESULT_SHA256, "H195 dependency hash mismatch")
    require(PROTOCOL.is_file() and INCIDENT.is_file(), "H196 protocol or incident missing")

    tracked = tracked_paths_with_renames(repo)
    hist = history(repo, tracked)
    trace = semantic_trace(repo)
    classification = "collision_resistant_identifier_recorded"
    require(classification in ALLOWED_CLASSIFICATIONS, "unsupported classification")
    require(trace["episode_uid_serialized_to_meta_json"], "classification lacks recorded UUID")
    require(trace["recording_locator_supplies_episode_to_rrd_join"], "classification lacks locator join")

    records = [
        {
            "path": path,
            "baseline": blob_record(repo, BASE, path),
            "comparison": blob_record(repo, HEAD, path),
        }
        for path in tracked
    ]
    require(
        next(r for r in records if r["path"] == "positronic/offboard/vendor_server.py")["comparison"]["present"]
        is False,
        "expected vendor_server deletion missing",
    )
    require(
        all(
            next(r for r in records if r["path"] == path)["comparison"]["present"]
            for path in EXPANSION_PATHS
        ),
        "required expansion missing at comparison endpoint",
    )

    return {
        "schema": "h196-positronic-session-identity-history-v1",
        "classification": classification,
        "interpretation": INTERPRETATION,
        "scope": (
            "Public Positronic v0.2.1-to-pinned-main source history and current "
            "PhAIL runtime-to-finalized-episode metadata path only"
        ),
        "limitations": LIMITATIONS,
        "dataset_content_opened": False,
        "performance_field_opened": False,
        "server_recording_opened": False,
        "private_service_accessed": False,
        "comparison_endpoint_prospective": True,
        "expansion_history_result_exposed": True,
        "protocol_sha256": sha256_file(PROTOCOL),
        "incident_sha256": sha256_file(INCIDENT),
        "h195_dependency_sha256": H195_RESULT_SHA256,
        "upstream": {
            "remote": REMOTE,
            "resolved_at": RESOLVED_AT,
            "baseline": commit_meta(repo, BASE),
            "comparison": commit_meta(repo, HEAD),
            "baseline_is_ancestor": True,
            "git_version": str(git(repo, "--version")).strip(),
        },
        "fixed_paths": list(FIXED_PATHS),
        "expansion_paths": list(EXPANSION_PATHS),
        "tracked_paths_after_rename_detection": list(tracked),
        "expansions": EXPANSIONS,
        "source_records": records,
        "history": {
            "status": "result_exposed_for_expansion_paths",
            "commit_count": len(hist),
            "commits": hist,
        },
        "trace": trace,
        "decision_consequence": (
            "Retain H195 as the historical v0.2.1 finding, but narrow P2's repair "
            "request: pinned current public code already records a UUID episode identity "
            "and the configured server-recording locator. The remaining request is to "
            "retain these fields in released evaluation artifacts and separately record "
            "physical reset/carryover and operator-session identity."
        ),
    }


def validate(result: dict[str, Any]) -> None:
    require(result.get("schema") == "h196-positronic-session-identity-history-v1", "schema mismatch")
    require(result.get("classification") in ALLOWED_CLASSIFICATIONS, "classification mismatch")
    require(result.get("comparison_endpoint_prospective") is True, "endpoint status mismatch")
    require(result.get("expansion_history_result_exposed") is True, "history exposure missing")
    for key in (
        "dataset_content_opened",
        "performance_field_opened",
        "server_recording_opened",
        "private_service_accessed",
    ):
        require(result.get(key) is False, f"prohibited access flag set: {key}")
    require(result.get("h195_dependency_sha256") == H195_RESULT_SHA256, "H195 dependency mismatch")
    require(result.get("fixed_paths") == list(FIXED_PATHS), "fixed path roster mismatch")
    require(result.get("expansion_paths") == list(EXPANSION_PATHS), "expansion roster mismatch")
    require(result.get("expansions") == EXPANSIONS, "expansion trace mismatch")
    commits = result.get("history", {}).get("commits")
    require(isinstance(commits, list) and commits, "history missing")
    require(result["history"].get("commit_count") == len(commits), "history count mismatch")
    require(len({item["commit"] for item in commits}) == len(commits), "duplicate history commit")
    trace = result.get("trace", {})
    require(trace.get("episode_uid_construction") == "uuid.uuid4().hex", "UUID construction mismatch")
    require(trace.get("episode_uid_serialized_to_meta_json") is True, "UUID persistence mismatch")
    require(
        trace.get("final_static_rrd_key") == "inference.policy.server.recording.rrd",
        "RRD static key mismatch",
    )
    require(trace.get("recording_locator_supplies_episode_to_rrd_join") is True, "RRD join mismatch")
    require(trace.get("physical_reset_or_operator_session_established") is False, "scope overreach")
    if result["classification"] == "collision_resistant_identifier_recorded":
        require(trace.get("episode_uid_serialized_to_meta_json") is True, "positive lacks UUID")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repository", type=Path, default=DEFAULT_REPOSITORY)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    candidate = build(args.repository)
    validate(candidate)
    rendered = json.dumps(candidate, indent=2, sort_keys=True) + "\n"
    if args.check:
        require(args.output.is_file(), f"stored result missing: {args.output}")
        require(args.output.read_text(encoding="utf-8") == rendered, "stored result differs from exact rebuild")
        print(f"PASS H196 exact check: {args.output}")
    else:
        args.output.write_text(rendered, encoding="utf-8")
        print(f"WROTE {args.output}")
        print(f"classification={candidate['classification']}")
        print(f"history_commits={candidate['history']['commit_count']}")


if __name__ == "__main__":
    main()
